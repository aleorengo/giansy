import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { addCustomToCart, addBundleToCart, addTimelessToCart, changeCartQuantity, restoreCart, validRequestedDate } from '../src/cart.ts';
import { isSelectionReady } from '../src/selection.ts';
const {products,packagingOptions}=JSON.parse(readFileSync(new URL('../src/data/catalog.json',import.meta.url)));
const ids=products.filter(p=>!p.bundleSize).map(p=>p.id);
const bundleIds=products.filter(p=>p.bundleSize).map(p=>p.id);
const steps=Object.fromEntries(products.map(p=>[p.id,p.quantityStep??1]));
const largeIds=products.filter(p=>p.size==='large').map(p=>p.id);
const valid=(selection,packagingId)=>Object.keys(selection).every(id=>ids.includes(id))&&isSelectionReady({selection,packagingId},packagingOptions,steps,largeIds);
const original={gingerbread:3,'christmas-star':3};
let cart=addCustomToCart([],original,'box');
original.gingerbread=99;
assert.equal(cart[0].selection.gingerbread,3,'Cart keeps a complete independent snapshot');
cart=addCustomToCart(cart,{'christmas-star':3,gingerbread:3},'box');
assert.equal(cart.length,1);assert.equal(cart[0].quantity,2,'Same assortment merges regardless of property order');
cart=changeCartQuantity(cart,cart[0].id,2);assert.equal(cart[0].quantity,4);
cart=addCustomToCart(cart,{'christmas-star':3,gingerbread:3},'paper');assert.equal(cart.length,2,'Different packaging stays separate');
cart=addBundleToCart(cart,bundleIds[0],4);assert.equal(cart[2].quantity,4);
cart=addBundleToCart(cart,bundleIds[0],2);assert.equal(cart[2].quantity,6);
assert.deepEqual(restoreCart(cart,bundleIds,valid),cart,'All packages and quantities survive reload');
assert.deepEqual(restoreCart([{kind:'bundle',productId:'unknown',quantity:1},{kind:'custom',selection:{unknown:1},packagingId:'paper',quantity:1},{kind:'custom',selection:{gingerbread:4},packagingId:'box',quantity:1}],bundleIds,valid),[]);
assert.deepEqual(restoreCart(null,bundleIds,valid),[]);
const timelessIds=products.filter(p=>(p.quantityStep??1)>1).map(p=>p.id);
let batches=addTimelessToCart([],timelessIds[0],1);
batches=addTimelessToCart(batches,timelessIds[0],2);
assert.equal(batches[0].quantity,3,'Three confirmed batches represent 45 pieces');
assert.deepEqual(restoreCart(batches,bundleIds,valid,timelessIds),batches);
assert.deepEqual(changeCartQuantity(batches,batches[0].id,-3),[]);
assert.deepEqual(addBundleToCart(cart,bundleIds[0],0),cart);
assert.deepEqual(changeCartQuantity(cart,cart[0].id,.5),cart);
cart=changeCartQuantity(cart,cart[2].id,-6);assert.equal(cart.length,2);
assert.deepEqual(products.filter(p=>p.bundleSize).map(p=>[p.price,p.bundleSize]),[[4.5,3],[15,12],[20,15]]);
assert.equal(validRequestedDate('2026-10-23','2026-10-23'),true);
assert.equal(validRequestedDate('2026-10-22','2026-10-23'),false);
assert.equal(validRequestedDate('2026-02-30','2026-01-01'),false);
assert.equal(validRequestedDate('2028-02-29','2026-01-01'),true);
assert.equal(validRequestedDate('','2026-10-23'),false);
console.log('Cart rules passed: independent snapshots, repeated packages, bundle quantities, persistence, invalid entries and requested dates.');
